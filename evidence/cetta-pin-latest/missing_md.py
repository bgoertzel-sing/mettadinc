#!/usr/bin/env python3
"""Render analysis/missing-{core,python}.tsv (classify_missing.py) as analysis/MISSING.md, the by-name list."""
import csv, os
B = chr(96)  # backtick
E = os.path.join(os.path.dirname(os.path.abspath(__file__)), "analysis")
import sys
R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(R, "tools"))
import cetta_baseline_check as c
RUN3_RHO = os.path.join(R, "evidence/cetta-pin-latest/cetta-baseline/latest-run3-swipl/04_test_rhocalc.log")
out = ["# Tests PASS at 12da03b4 (E0's frozen logs) and not PASS at 4c285a97, by name", "",
"Core and python lanes: latest-run2-overrides; latest-run3-swipl (the same plus SWI-Prolog 9.2.9 on PATH) has exactly",
"the same PASS/SKIP/FAIL multisets in both lanes, so these tables hold for it too. Rhocalc lane: latest-run3-swipl.", "",
"Generated by evidence/cetta-pin-latest/missing_md.py from missing-core.tsv and missing-python.tsv",
"(classify_missing.py). Lines are normalised as in tools/cetta_baseline_check.py (digits become N). Categories:", "",
"- **rhocalc-suite**: one of the rhocalc suite's lines (also in E0's 07 log). At 12da03b4 test-correctness ran the",
"  rhocalc suite; at 4c285a97 it does not (NORMAL_TEST_TARGETS, Makefile:19038), so these lines are only in the",
"  rhocalc lane, which runs with SWI-Prolog 9.2.9 (latest-run3-swipl; without swipl it stops before any test, as in",
"  latest-run2-overrides). Listed once, at the end, with their status in that rhocalc lane.",
"- **gone-upstream**: the test's text or file is in the 12da03b4 tree and nowhere in the 4c285a97 tree (removed or renamed).",
"- **not-reached:<target>**: still defined at 4c285a97 in that Makefile target, which test-correctness and test-profiles",
"  no longer reach (static prerequisites).",
"- **unlocated**: the text is composed at run time or lives in a helper script, so no single target was named;",
"  'found in neither tree' means the exact line is composed (e.g. a loop over feature names).", ""]
def rows(lane):
    return list(csv.reader(open(os.path.join(E, f"missing-{lane}.tsv")), delimiter="\t"))
for lane in ("core", "python"):
    rs = rows(lane)
    tot = sum(int(r[4][1:]) for r in rs); rho = sum(int(r[4][1:]) for r in rs if r[2] == "rhocalc-suite")
    out += [f"## {lane} lane: {tot} lines ({rho} rhocalc-suite, {tot - rho} others below)", "",
            "| Line | Category | Detail | Count |", "|---|---|---|---|"]
    for r in rs:
        if r[2] == "rhocalc-suite":
            continue
        cat, det = r[2], r[3]
        if r[1] == "PASS: mmN has no named profiles":
            cat = "gone-upstream"
            det = ("checked by hand: 'mm2 has no named profiles' is at Makefile:6167 at 12da03b4 and nowhere at "
                   "4c285a97 (the classifier had matched an unrelated 'prime' check)")
        out.append(f"| {B}{r[1].replace('|', '/')}{B} | {cat} | {det.replace('|', '/')} | {r[4]} |")
    out.append("")
# Renames checked by hand (git diff -M 12da03b4 4c285a97, and scripts/rhocalc_cost_parallel_stress.py:240):
HAND = {
    "PASS: cost-rho parallel stress independent-surfaces": ("PASS: cost-rho parallel stress independent-locations",
        "scripts/rhocalc_cost_parallel_stress.py:240, case renamed"),
    "PASS: rhocalc lib/rho surface tests/test_lts_rho_cost_surface.metta":
        ("PASS: rhocalc lib/rho syntax tests/test_lts_rho_cost_location.metta", "git: R099 test_lts_rho_cost_surface.metta -> test_lts_rho_cost_location.metta"),
    "PASS: rhocalc quiescent/open-name contract tests/rhocalc/surface_open_name_variable.rho":
        ("PASS: rhocalc quiescent/open-name contract tests/rhocalc/rho_open_name_variable.rho", "git: .expected R100 surface_open_name_variable -> rho_open_name_variable"),
    "PASS: tests/rhocalc_run/pipeline_two_forwarders_surface.rho": ("PASS: tests/rhocalc_run/pipeline_two_forwarders_rho.rho",
        "git: R066 .rho, R100 .expected"),
    "PASS: tests/rhocalc_run/quiescent_nil_surface.rho": ("PASS: tests/rhocalc_run/quiescent_nil_rho.rho", "git: R100"),
}
now = c.parse(RUN3_RHO, os.path.join(R, "cetta"))["PASS"]
rho = [r for r in rows("core") if r[2] == "rhocalc-suite"]
same, renamed, other = [], [], []
for r in rho:
    line, n = r[1], int(r[4][1:])
    if now[line] >= n:
        same.append(r)
    elif "surface" in line and now[line.replace("surface", "syntax")] >= n:
        renamed.append((r, line.replace("surface", "syntax"), "only 'surface' -> 'syntax' in the name"))
    elif line in HAND and now[HAND[line][0]] >= n:
        renamed.append((r, HAND[line][0], HAND[line][1]))
    else:
        other.append(r)
tot = sum(int(r[4][1:]) for r in rho)
out += [f"## rhocalc-suite lines (rhocalc lane): {tot} lines; at 4c285a97 with SWI-Prolog (latest-run3-swipl): "
        f"{sum(int(r[4][1:]) for r in same)} PASS under the same name, {len(renamed)} PASS under a new name, "
        f"{sum(int(r[4][1:]) for r in other)} not PASS", "",
        "The renamed ones (old line -> new line PASS in latest-run3-swipl, evidence):", ""]
for r, new, why in renamed:
    out.append(f"- {B}{r[1]}{B} -> {B}{new}{B} ({why})")
out += ["", "Not PASS under any name found:" + (" none." if not other else ""), ""]
for r in other:
    out.append(f"- {B}{r[1]}{B}" + (f" ({r[4]})" if r[4] != "x1" else ""))
out += ["", "PASS under the same name (for completeness):", ""]
for r in same:
    out.append(f"- {B}{r[1]}{B}" + (f" ({r[4]})" if r[4] != "x1" else ""))
open(os.path.join(E, "MISSING.md"), "w").write("\n".join(out) + "\n")
