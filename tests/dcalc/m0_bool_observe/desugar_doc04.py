#!/usr/bin/env python3
"""Desugar doc04's AnchorMigration and TaskResume (docs/e0/docs/04_omega_memory_goals_part1/validation_bundle/
memory_goals.metta l.341-411) into forms the Crisp M0 lowering already admits, keeping every (To Bool) Observe
map: type-form From/To (blocker b) become named carriers, If/Eq/And/Or/Not case bodies (blocker c) and Body maps
are evaluated here into one literal-pattern Cases row per input, and (Machine Resume (States Live) (Like Restart)) (blocker d) gets Restart's
Observe and Action entries copied.  The Bool-in-tuple code of checkpoint-without-reads uses an Enum carrier
B2 = {False, True} (Bool inside a tuple is not this task's form).  The output, fixtures/doc04_desugared.metta, is
a cross-check that the Bool Observe lowering gives doc04's stated answers once the other blockers are removed by
hand; it is not the doc04 module.  Run: python3 desugar_doc04.py > fixtures/doc04_desugared.metta"""
import itertools

def tup(*xs): return '(Tuple %s)' % ' '.join(xs)
def b(x): return 'True' if x else 'False'
def table(name, frm, to, dom, f):
    rows = ' '.join('(%s %s)' % (tup(*x), f(*x)) for x in dom)
    return '  (Map %s (From %s) (To %s) (Cases %s))' % (name, frm, to, rows)   # literal-pattern Cases (Subset needs Cases)

out = [';; GENERATED by desugar_doc04.py from doc04 memory_goals.metta l.341-411; do not edit by hand.',
       ';; doc04 answers: NaiveMigration Refuted (s6.4 l.1422), CellMigration Checked (l.1425);',
       ';; NoReadSets CheckNow Checked, CheckUpdates Refuted, CheckBehavioral Refuted, ReadSets CheckBehavioral Checked,',
       ';; ResumeMemory 11 classes on 12 states (s7.3 l.1518-1524).']
# ---- AnchorMigration ----
old_all = list(itertools.product(['present', 'absent'], ['old', 'none']))
new_all = list(itertools.product(['present', 'absent'], ['new', 'old', 'none']))
oc = lambda g, l: (g == 'present' and l == 'old') or (g == 'absent' and l == 'none')
nc = lambda g, l: (g == 'present' and l != 'none') or (g == 'absent' and l == 'none')
rep = lambda new: (lambda g, l: tup('present', new) if g == 'absent' else tup(g, l))
out += ['(DC.Module AnchorMigrationD', '  (Profile Crisp)',
        '  (Carrier Atom    (Of Symbol) (Enum present absent))',
        '  (Carrier OldLink (Of Symbol) (Enum old none))',
        '  (Carrier NewLink (Of Symbol) (Enum new old none))',
        '  (Carrier OldAll   (Of (Tuple Symbol Symbol)) (Product Atom OldLink))',
        '  (Carrier NewAll   (Of (Tuple Symbol Symbol)) (Product Atom NewLink))',
        table('old-consistent', 'OldAll', 'Bool', old_all, lambda g, l: b(oc(g, l))),
        table('new-consistent', 'NewAll', 'Bool', new_all, lambda g, l: b(nc(g, l))),
        '  (Carrier OldState (Of (Tuple Symbol Symbol)) (Subset OldAll old-consistent))',
        '  (Carrier NewState (Of (Tuple Symbol Symbol)) (Subset NewAll new-consistent))',
        table('lesion-o', 'OldAll', 'OldAll', old_all, lambda g, l: tup('absent', 'none')),
        table('lesion-n', 'NewAll', 'NewAll', new_all, lambda g, l: tup('absent', 'none')),
        table('repair-old', 'OldAll', 'OldAll', old_all, rep('old')),
        table('repair-naive', 'NewAll', 'NewAll', new_all, rep('old')),
        table('repair-cell', 'NewAll', 'NewAll', new_all, rep('new')),
        table('live-old', 'OldAll', 'Bool', old_all, lambda g, l: b(l == 'old')),
        table('live-new', 'NewAll', 'Bool', new_all, lambda g, l: b(l == 'new')),
        '  (Machine Before     (States OldState) (Observe live live-old) (Action lesion lesion-o) (Action repair repair-old))',
        '  (Machine AfterNaive (States NewState) (Observe live live-new) (Action lesion lesion-n) (Action repair repair-naive))',
        '  (Machine AfterCell  (States NewState) (Observe live live-new) (Action lesion lesion-n) (Action repair repair-cell))',
        table('rename', 'OldState', 'NewState', [x for x in old_all if oc(*x)], lambda g, l: tup(g, 'new') if l == 'old' else tup(g, l)),
        '  (AbstractionMap NaiveMigration (Source Before) (Target AfterNaive) (Map rename))',
        '  (AbstractionMap CellMigration  (Source Before) (Target AfterCell)  (Map rename)))',
        '!(dc.run AnchorMigrationD (CheckAbstractionMap NaiveMigration))',
        '!(dc.run AnchorMigrationD (CheckAbstractionMap CellMigration))']
# ---- TaskResume ----
task = list(itertools.product(['valid', 'withdrawn'], ['valid', 'withdrawn'], ['none', 'r1', 'r2'], ['current', 'stale']))
def derive(k):
    def f(v1, v2, r, fl):
        v = v1 if k == 1 else v2
        return tup(v1, v2, 'r%d' % k, 'current') if (v == 'valid' and r == 'none') else tup(v1, v2, r, fl)
    return f
w1 = lambda v1, v2, r, f: tup('withdrawn', v2, r, 'stale' if r == 'r1' else f)
w2 = lambda v1, v2, r, f: tup(v1, 'withdrawn', r, 'stale' if r == 'r2' else f)
rv = lambda v1, v2, r, f: tup(v1, v2, 'none', 'current') if f == 'stale' else tup(v1, v2, r, f)
obs = ['(Observe needs-revalidation needs-revalidation)', '(Observe available available)']
acts = ['(Action %s %s)' % (a, a) for a in ('derive1', 'derive2', 'withdraw1', 'withdraw2', 'revalidate')]
out += ['(DC.Module TaskResumeD', '  (Profile Crisp)',
        '  (Carrier Ev   (Of Symbol) (Enum valid withdrawn))',
        '  (Carrier Res  (Of Symbol) (Enum none r1 r2))',
        '  (Carrier Flag (Of Symbol) (Enum current stale))',
        '  (Carrier B2   (Of Symbol) (Enum False True))',
        '  (Carrier Task (Of (Tuple Symbol Symbol Symbol Symbol)) (Product Ev Ev Res Flag))',
        '  (Carrier Code (Of (Tuple Symbol Symbol Symbol Symbol)) (Product Ev Ev B2 Flag))',
        '  (Const start Task (Tuple valid valid none current))',
        table('derive1', 'Task', 'Task', task, derive(1)),
        table('derive2', 'Task', 'Task', task, derive(2)),
        table('withdraw1', 'Task', 'Task', task, w1),
        table('withdraw2', 'Task', 'Task', task, w2),
        table('revalidate', 'Task', 'Task', task, rv),
        table('needs-revalidation', 'Task', 'Bool', task, lambda v1, v2, r, f: b(f == 'stale')),
        table('available', 'Task', 'Bool', task, lambda v1, v2, r, f: b(r != 'none' and f == 'current')),
        '  (Machine Restart (States Task) %s %s)' % (' '.join(obs), ' '.join(acts)),
        '  (Carrier Live (Of (Tuple Symbol Symbol Symbol Symbol)) (Reach Restart (From start)))',
        '  (Machine Resume (States Live) %s %s)' % (' '.join(obs), ' '.join(acts)),
        table('checkpoint-without-reads', 'Task', 'Code', task, lambda v1, v2, r, f: tup(v1, v2, b(r != 'none'), f)),
        table('checkpoint-with-reads', 'Task', 'Task', task, lambda *x: tup(*x)),
        '  (Representation NoReadSets (Of Resume) (Encode checkpoint-without-reads))',
        '  (Representation ReadSets   (Of Resume) (Encode checkpoint-with-reads))',
        '  (Derive ResumeMemory (MinimizeForQueries Resume)))',
        '!(dc.run TaskResumeD (CheckNow NoReadSets))',
        '!(dc.run TaskResumeD (CheckUpdates NoReadSets))',
        '!(dc.run TaskResumeD (CheckBehavioral NoReadSets))',
        '!(dc.run TaskResumeD (CheckBehavioral ReadSets))',
        '!(dc.run TaskResumeD ResumeMemory)']
print('\n'.join(out))
