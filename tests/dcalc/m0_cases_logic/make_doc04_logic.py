#!/usr/bin/env python3
"""Build fixtures/doc04_logic.metta from doc04's AnchorMigration and TaskResume (docs/e0/docs/
04_omega_memory_goals_part1/validation_bundle/memory_goals.metta, excerpts anchor-migration and task-resume).

Every If/Eq/And/Or/Not case body (blocker c, this task's form) is kept verbatim.  Only the forms that other
gaps still block are rewritten, each by one exact textual replacement that must hit exactly once:
  AnchorMigration: the Bool Observe maps live-old/live-new are declared (From OldAll)/(From NewAll) instead of
    (From (Tuple Symbol Symbol)) (a (To Bool) Observe map with a type-form From is not lowered: neither the
    bool-observe nor the type-form lowering takes it); lesion's (Body ($x) (Tuple absent none)) becomes the Cases
    row ((Tuple $g $l) (Tuple absent none)) (blocker f, Body map in a Crisp module).
  TaskResume: (Machine Resume (States Live) (Like Restart)) gets Restart's Observe and Action entries copied
    (blocker d); checkpoint-with-reads' (Body ($x) $x) becomes ((Tuple $v1 $v2 $r $f) (Tuple $v1 $v2 $r $f)) (f).
Modules are renamed AnchorMigrationL / TaskResumeL.  The output is a cross-check that the lowering gives doc04's
stated answers with doc04's own logic bodies; it is not the doc04 module.
Run: python3 make_doc04_logic.py > fixtures/doc04_logic.metta"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
SRC = os.path.join(ROOT, 'docs', 'e0', 'docs', '04_omega_memory_goals_part1', 'validation_bundle', 'memory_goals.metta')
text = open(SRC).read()

def excerpt(name):
    m = re.search(r';; @excerpt %s\n(.*?);; @end' % re.escape(name), text, re.S)
    if not m: sys.exit('excerpt %s not found' % name)
    return m.group(1)

def sub(s, old, new):
    if s.count(old) != 1: sys.exit('replacement must hit exactly once: %r (%d hits)' % (old, s.count(old)))
    return s.replace(old, new)

am = excerpt('anchor-migration')
am = sub(am, '(DC.Module AnchorMigration\n', '(DC.Module AnchorMigrationL\n')
am = sub(am, '(Map live-old (From (Tuple Symbol Symbol)) (To Bool)', '(Map live-old (From OldAll) (To Bool)')
am = sub(am, '(Map live-new (From (Tuple Symbol Symbol)) (To Bool)', '(Map live-new (From NewAll) (To Bool)')
am = sub(am, '(Body ($x) (Tuple absent none))', '(Cases ((Tuple $g $l) (Tuple absent none)))')
tr = excerpt('task-resume')
tr = sub(tr, '(DC.Module TaskResume\n', '(DC.Module TaskResumeL\n')
ports = re.search(r'\(Machine Restart \(States Task\)(.*?)\)\n  \(Carrier Live', tr, re.S).group(1)
ports = ' '.join(ports.split())
tr = sub(tr, '(Machine Resume (States Live) (Like Restart))', '(Machine Resume (States Live) %s)' % ports)
tr = sub(tr, '(Body ($x) $x)', '(Cases ((Tuple $v1 $v2 $r $f) (Tuple $v1 $v2 $r $f)))')
reqs = lambda name: [l.replace('(dc.run %s ' % name, '(dc.run %sL ' % name) for l in excerpt(name.lower().replace('anchormigration', 'anchor-migration').replace('taskresume', 'task-resume') + '-requests').splitlines() if l.startswith('!(dc.run')]
out = [';; GENERATED by make_doc04_logic.py from docs/e0 doc04 memory_goals.metta (excerpts anchor-migration, task-resume);',
       ';; do not edit by hand.  If/Eq/And/Or/Not bodies verbatim; only forms of other gaps rewritten (see the script).',
       ';; doc04 answers: NaiveMigration Refuted (s6.4 l.1422), CellMigration Checked (l.1425); NoReadSets CheckNow Checked,',
       ';; CheckUpdates Refuted, CheckBehavioral Refuted, ReadSets CheckBehavioral Checked, ResumeMemory 11 classes on 12 states (s7.3).',
       am.rstrip('\n')] + reqs('AnchorMigration') + [tr.rstrip('\n')] + reqs('TaskResume')
print('\n'.join(out))
