#!/usr/bin/env python3
"""Gates for t-2026-11-23-mettadinc-m0-cases-logic: If/Eq/And/Or/Not inside Cases bodies of Crisp M0 maps
(spec 5.1 grammar l.1721, map-body ::= (Cases (pattern expr)+); spec 5.4 l.1858, admitted expressions include
registered pure primitives; registry libraries.Core.primitives lists Eq, If, Not, And, Or).
Every gate runs in release mode and with --beyond-release.
  1. probe P3 (examples_e2e/repro/m0_blocker_c_if_eq_cases.metta): C1 Checked, answering exactly as its literal-Cases
     control C1C (module name and digest masked);
  2. fixtures/logic_gates.metta: every status and witness equals Ben's reference evaluator (docs/e0 mg_eval.World +
     models/dclib, through ../m0_typeform_maps/reference_answers.py), and every module LGn answers exactly as its
     literal-Cases twin LGnC (Refuted and Checked cases, so a lowering with another meaning fails);
  3. fixtures/doc04_logic.metta (generated by make_doc04_logic.py from doc04, logic bodies verbatim): doc04's seven
     stated answers, and the reference evaluator's status and witness on the five requests it can run;
  4. fixtures/logic_negative.metta: malformed uses answer InvalidInput, each with its reason;
  5. fixtures/logic_unsupported.metta: forms still outside the fragment answer Unsupported, the reason naming the form.
DCALC overrides the binary (used to show the gate fails on the base binary and on mutants)."""
import os, re, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
DC = os.environ.get('DCALC') or os.path.join(ROOT, 'build', 'dcalc', 'dcalc')
FXD = os.path.join(HERE, 'fixtures')
PROBE = os.path.join(ROOT, 'tests', 'dcalc', 'examples_e2e', 'repro', 'm0_blocker_c_if_eq_cases.metta')
REF = os.path.join(ROOT, 'tests', 'dcalc', 'm0_typeform_maps', 'reference_answers.py')
fails = 0
def report(name, ok, det=''):
    global fails
    print(('PASS  ' if ok else 'FAIL  ') + name + ('' if ok else '  :: ' + str(det)[:400]))
    if not ok: fails += 1
def rows(path, args=()):
    o = subprocess.run([DC] + list(args) + [path], capture_output=True, text=True, timeout=300)
    out = {}
    for l in o.stdout.splitlines():
        if ' => ' not in l: continue
        k, v = l.split(' => ', 1)
        st = re.search(r'\(Status ([A-Za-z]+)\)', v); rs = re.search(r'\(Reason "([^"]*)"', v)
        out[k.strip()] = (st.group(1) if st else None, rs.group(1) if rs else '', v)
    return out
def strip_ids(v):
    v = re.sub(r'\(Module [^()\s]+\)', '(Module _)', v)
    return re.sub(r'\(Digest "[0-9a-f]*"\)', '(Digest _)', v)
def reference(path):
    rp = subprocess.run([sys.executable, REF, path], capture_output=True, text=True, timeout=300)
    ref = {}
    for l in rp.stdout.splitlines():
        k, st, w = l.split('\t'); ref[k] = (st, w)
    return rp, ref
def witness_ok(g, st, w):
    ok = g is not None and g[0] == st
    if ok and w != '-':
        ok = all(part in g[2] for part in re.findall(r'\((?:Pair|State|Action|Observe) (?:[^()]|\([^()]*\))*\)', w))
    return ok

GATES = os.path.join(FXD, 'logic_gates.metta')
rp, ref = reference(GATES)
report('reference evaluator ran on logic_gates.metta (docs/e0 mg_eval + dclib) and answered all 32 requests', rp.returncode == 0 and len(ref) == 32, rp.stderr[-300:])
# doc04 with logic bodies verbatim: the generator's output is the committed fixture
DOC = os.path.join(FXD, 'doc04_logic.metta')
gen = subprocess.run([sys.executable, os.path.join(HERE, 'make_doc04_logic.py')], capture_output=True, text=True, timeout=60).stdout
report('doc04_logic.metta is the output of make_doc04_logic.py (doc04 text, logic bodies verbatim)', gen == open(DOC).read())
tmp = tempfile.NamedTemporaryFile('w', suffix='.metta', delete=False)
tmp.write('\n'.join(l for l in open(DOC).read().splitlines() if not (l.startswith('!(dc.run') and ('CheckBehavioral' in l or 'ResumeMemory' in l))) + '\n'); tmp.close()
rpd, refd = reference(tmp.name); os.unlink(tmp.name)
report('reference evaluator ran on doc04_logic.metta (CheckNow/CheckUpdates/CheckAbstractionMap requests: 4)', rpd.returncode == 0 and len(refd) == 4, rpd.stderr[-300:])
DOC04 = [  # doc04's stated answers: s6.4 l.1422 / l.1425, s7.3 l.1518-1524
    ('AnchorMigrationL (CheckAbstractionMap NaiveMigration)', 'Refuted'),
    ('AnchorMigrationL (CheckAbstractionMap CellMigration)', 'Checked'),
    ('TaskResumeL (CheckNow NoReadSets)', 'Checked'),
    ('TaskResumeL (CheckUpdates NoReadSets)', 'Refuted'),
    ('TaskResumeL (CheckBehavioral NoReadSets)', 'Refuted'),
    ('TaskResumeL (CheckBehavioral ReadSets)', 'Checked'),
    ('TaskResumeL ResumeMemory', 'Checked'),
]
NEG = {
    'NA (CheckNow R)': 'Map ob: Cases row 0 on a: the condition of (If ...) gives a, which is not True or False',
    'NB (CheckNow R)': 'Map ob: Cases row 0 on a: (If ...) takes 3 arguments (condition, then, else), not 2',
    'NC (CheckNow R)': 'Map ob: Cases row 0 on a: (Eq ...) takes 2 arguments, not 1',
    'ND (CheckNow R)': 'Map ob: Cases row 0 on a: operand 1 of (Not ...) gives a, which is not True or False',
    'NE (CheckNow R)': 'Map ob: Cases row 0 on a: operand 2 of (And ...) gives a, which is not True or False',
    'NF (CheckNow R)': 'Map ob: Cases row 0 on a: operand 2 of (Or ...) gives a, which is not True or False',
    'NG (CheckNow R)': 'Map ob: Cases row 0 gives a value outside carrier S',
    'NH (CheckNow R)': 'Map pick: Cases row 0 on (Tuple p p): (Not ...) takes 1 argument, not 2',
    'NI (CheckNow R)': 'Carrier T: Subset predicate keep on a: the condition of (If ...) gives a, which is not True or False',
}
UNS = {
    'UA (CheckNow R)': 'Map ob: Cases row 0: (And ...) with 1 operand is outside the M0 fragment',
    'UB (CheckNow R)': 'Map ob: Cases row 0: (Or ...) with 0 operands is outside the M0 fragment',
    'UC (CheckNow R)': 'Map ob: Cases row 0: (Eq ...) reads the Const ka',
    'UD (CheckNow R)': 'Map ob: Cases row 0: (If ...) in a Cases body is lowered only in a Crisp module, not in profile Graded',
    'UE (CheckNow R)': 'Representation R is outside the M0 fragment',
}
for mode in ([], ['--beyond-release']):
    tag = ' [%s]' % (mode[0] if mode else 'release')
    r = rows(PROBE, mode)
    c, cc = r.get('C1 (CheckNow R)'), r.get('C1C (CheckNow R)')
    report('probe P3: C1 (If/Eq in a Cases body) -> Checked' + tag, c is not None and c[0] == 'Checked', c)
    report('probe P3: C1 answers exactly as its literal-Cases control C1C' + tag, c is not None and cc is not None and strip_ids(c[2]) == strip_ids(cc[2]), (c, cc))
    r = rows(GATES, mode)
    for k, (st, w) in sorted(ref.items()):
        report('%s -> %s %s (reference evaluator)%s' % (k, st, '' if w == '-' else w, tag), witness_ok(r.get(k), st, w), r.get(k))
    for k in sorted(ref):
        mod = k.split(' ', 1)[0]
        if mod.endswith('C'): continue
        twin = mod + 'C' + k[len(mod):]
        g, h = r.get(k), r.get(twin)
        report('%s answers exactly as its literal-Cases twin %s%s' % (k, twin, tag), g is not None and h is not None and strip_ids(g[2]) == strip_ids(h[2]), (g, h))
    r = rows(DOC, mode)
    for k, st in DOC04:
        g = r.get(k)
        report('doc04 logic-verbatim %s -> %s (doc04)%s' % (k, st, tag), g is not None and g[0] == st, g)
    for k, (st, w) in sorted(refd.items()):
        report('doc04 logic-verbatim %s -> %s %s (reference evaluator)%s' % (k, st, '' if w == '-' else w, tag), witness_ok(r.get(k), st, w), r.get(k))
    g = r.get('TaskResumeL ResumeMemory')
    blocks = re.findall(r'\(Block ((?:[^()]|\([^()]*\))*)\)', g[2].split('(Partition', 1)[1].split('(Evidence', 1)[0]) if g and '(Partition' in g[2] else []
    nstates = sum(len(re.findall(r'\(Tuple [^()]*\)', b)) for b in blocks)
    report('doc04 logic-verbatim ResumeMemory: 11 classes on 12 states (doc04 s7.3 l.1524)' + tag, len(blocks) == 11 and nstates == 12, (len(blocks), nstates))
    r = rows(os.path.join(FXD, 'logic_negative.metta'), mode)
    for k, why in NEG.items():
        g = r.get(k)
        report('negative %s -> InvalidInput: %s%s' % (k, why, tag), g is not None and g[0] == 'InvalidInput' and why in g[1], g)
    r = rows(os.path.join(FXD, 'logic_unsupported.metta'), mode)
    for k, why in UNS.items():
        g = r.get(k)
        report('outside %s -> Unsupported: %s%s' % (k, why, tag), g is not None and g[0] == 'Unsupported' and why in g[1], g)
print('%s: %d failed' % ('FAIL' if fails else 'PASS', fails))
sys.exit(1 if fails else 0)
