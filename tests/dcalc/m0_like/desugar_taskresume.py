#!/usr/bin/env python3
"""Make fixtures/taskresume_like.metta: doc04's TaskResume module (memory_goals.metta:390-433) with every
form except (Machine Resume (States Live) (Like Restart)) rewritten into the current Crisp M0 fragment, so
that Like is the only form under test (t-2026-11-23-mettadinc-m0-like-machines).

Ben's reference evaluator (docs/e0/.../04_omega_memory_goals_part1/validation_bundle/mg_eval.py) reads the
original module and evaluates every map on every element of its declared domain; each map is written out as
a (Table (in out) ...) with those values.  The other M0 gaps are therefore sidestepped, not lowered:
  (a) Bool Observe maps -> maps into (Carrier YN (Of Symbol) (Enum False True));
  (b) the type-form To of checkpoint-without-reads -> a declared Product carrier NoReadCode;
      checkpoint-with-reads (To (Tuple ...)), the identity, -> (To Task);
  (c) If/Eq/And/Or/Not Cases bodies -> Table rows computed by the reference evaluator;
  the (Const start ...) is written inline in (From ...).
Two modules: TRL keeps (Machine Resume (States Live) (Like Restart)); TRW is the control with Resume's
entries written out.  Requests: the five TaskResume requests of doc04 (memory_goals.metta:437-441).

    python3 tests/dcalc/m0_like/desugar_taskresume.py           # rewrite the fixture
    python3 tests/dcalc/m0_like/desugar_taskresume.py --check   # exit 1 if the fixture differs
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
BUNDLE = os.path.join(ROOT, 'docs', 'e0', 'docs', '04_omega_memory_goals_part1', 'validation_bundle')
sys.path[:0] = [BUNDLE, os.path.join(BUNDLE, 'models')]
from mg_eval import World  # noqa: E402

OUT = os.path.join(HERE, 'fixtures', 'taskresume_like.metta')
MOD = 'TaskResume'

def fmt(v):
    if isinstance(v, bool): return 'True' if v else 'False'
    if isinstance(v, tuple): return '(Tuple ' + ' '.join(fmt(x) for x in v) + ')'
    return str(v)

def build():
    w = World(os.path.join(BUNDLE, 'memory_goals.metta'))
    task = w.carrier(MOD, 'Task')
    def table(name, to):
        f = w.fn(MOD, name)
        rows = ' '.join('(%s %s)' % (fmt(x), fmt(f(x))) for x in task)
        return '  (Map %s (From Task) (To %s)\n    (Table %s))\n' % (name, to, rows)
    start = fmt(w.ev(MOD, 'start', {}, {}))
    acts = ['derive1', 'derive2', 'withdraw1', 'withdraw2', 'revalidate']
    obs = ['needs-revalidation', 'available']
    entries = ''.join(' (Observe %s %s)' % (o, o) for o in obs) + ''.join(' (Action %s %s)' % (a, a) for a in acts)
    def module(name, resume):
        s = '(DC.Module %s\n  (Profile Crisp)\n' % name
        s += '  (Carrier Ev   (Of Symbol) (Enum valid withdrawn))\n'
        s += '  (Carrier Res  (Of Symbol) (Enum none r1 r2))\n'
        s += '  (Carrier Flag (Of Symbol) (Enum current stale))\n'
        s += '  (Carrier YN   (Of Symbol) (Enum False True))\n'
        s += '  (Carrier Task (Of (Tuple Symbol Symbol Symbol Symbol)) (Product Ev Ev Res Flag))\n'
        s += '  (Carrier NoReadCode (Of (Tuple Symbol Symbol Symbol Symbol)) (Product Ev Ev YN Flag))\n'
        for a in acts: s += table(a, 'Task')
        for o in obs: s += table(o, 'YN')
        s += '  (Machine Restart (States Task)%s)\n' % entries
        s += '  (Carrier Live (Of (Tuple Symbol Symbol Symbol Symbol)) (Reach Restart (From %s)))\n' % start
        s += resume
        s += table('checkpoint-without-reads', 'NoReadCode')
        s += table('checkpoint-with-reads', 'Task')
        s += '  (Representation NoReadSets (Of Resume) (Encode checkpoint-without-reads))\n'
        s += '  (Representation ReadSets   (Of Resume) (Encode checkpoint-with-reads))\n'
        s += '  (Derive ResumeMemory (MinimizeForQueries Resume)))\n'
        for rq in ('(CheckNow NoReadSets)', '(CheckUpdates NoReadSets)', '(CheckBehavioral NoReadSets)',
                   '(CheckBehavioral ReadSets)', 'ResumeMemory'):
            s += '!(dc.run %s %s)\n' % (name, rq)
        return s
    head = (';; GENERATED by tests/dcalc/m0_like/desugar_taskresume.py from doc04 memory_goals.metta TaskResume\n'
            ';; (see that script).  TRL: Resume by (Like Restart), the form under test.  TRW: Resume written out.\n')
    return head + module('TRL', '  (Machine Resume (States Live) (Like Restart))\n') + '\n' + \
        module('TRW', '  (Machine Resume (States Live)%s)\n' % entries)

if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('taskresume_like.metta: %s' % ('up to date' if same else 'DIFFERS from the generator'))
        sys.exit(0 if same else 1)
    with open(OUT, 'w') as fh: fh.write(text)
    print('wrote', OUT)
