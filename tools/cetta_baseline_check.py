#!/usr/bin/env python3
"""Parse Cetta baseline logs and compare them with tools/cetta-baseline.expected.

Used by tools/cetta-baseline.sh (compare) and, once, to derive the expected file from E0's frozen
logs (docs/e0/evidence/cetta/07, 08, 10) with `expected-from-logs`.  Standard library only.

A log is summarised as:
  exit      the make exit status (EXIT=<n> line written by the harness, or E0's EXIT= line)
  final     the last "<n> passed, <m> failed" line (rhocalc lane)
  PASS/SKIP/FAIL lines (lines starting with those words), normalised: the absolute Cetta path
            becomes <CETTA>, every run of digits becomes N (timings, RSS sizes, counts)
  targets   failed make targets, from "make: *** [Makefile:<line>: <target>] Error <n>"

Verdict for a lane: red if a PASS line of the expected multiset is missing (or the PASS count is
lower), if any SKIP or FAIL line or failed make target is not in the expected multisets (new
skip/failure), if the rhocalc final line differs, or if an exit status the expected file pins
differs.  Expected skips or failures that disappear are reported as improvements, not as red.
"""
import collections
import re
import sys

E0_CETTA = "/home/openclaw/research-agent/projects/mettadinc/repos/cetta"
TARGET_RE = re.compile(r"^make(?:\[\d+\])?: \*\*\* \[Makefile:\d+: ([^\]]+)\] Error \d+")
FINAL_RE = re.compile(r"^(\d+) passed, (\d+) failed\s*$")


def norm(line, cetta_dir):
    line = line.rstrip("\n").rstrip()
    for d in (cetta_dir, E0_CETTA):
        if d:
            line = line.replace(d, "<CETTA>")
    return re.sub(r"\d+", "N", line)


def parse(path, cetta_dir=None):
    s = {"exit": None, "final": None, "PASS": collections.Counter(), "SKIP": collections.Counter(),
         "FAIL": collections.Counter(), "targets": collections.Counter(), "npass": 0}
    for raw in open(path, errors="replace"):
        line = raw.rstrip("\n")
        m = re.match(r"^EXIT=(\d+)", line)
        if m:
            s["exit"] = int(m.group(1))
            continue
        m = FINAL_RE.match(line.strip())
        if m:
            s["final"] = (int(m.group(1)), int(m.group(2)))
        m = TARGET_RE.match(line)
        if m:
            s["targets"][m.group(1)] += 1
            continue
        for k in ("PASS", "SKIP", "FAIL"):
            if line.startswith(k):
                s[k][norm(line, cetta_dir)] += 1
                if k == "PASS":
                    s["npass"] += 1
    return s


def write_expected(lanes, out):
    """lanes: list of (lane, logpath, pin_exit)"""
    with open(out, "w") as f:
        f.write("# Cetta baseline expected results (Ben's decision 2: no regression against E0's frozen baseline at 12da03b4).\n")
        f.write("# Generated by tools/cetta_baseline_check.py expected-from-logs from E0's logs, never from a new run:\n")
        for lane, path, _ in lanes:
            f.write(f"#   {lane}: {path}\n")
        f.write("# Lines: lane <name>; exit <n>; final <passed> <failed>; npass <n>; and one line per entry of the\n")
        f.write("# multisets: pass|skip|fail <normalised line>, target <failed make target>.\n")
        for lane, path, pin_exit in lanes:
            s = parse(path)
            f.write(f"\nlane {lane}\n")
            if pin_exit:
                f.write(f"exit {s['exit']}\n")
            if lane == "rhocalc":
                f.write(f"final {s['final'][0]} {s['final'][1]}\n")
            f.write(f"npass {s['npass']}\n")
            for k, tag in (("SKIP", "skip"), ("FAIL", "fail"), ("targets", "target")):
                for line, n in sorted(s[k].items()):
                    for _ in range(n):
                        f.write(f"{tag} {line}\n")
            for line, n in sorted(s["PASS"].items()):
                for _ in range(n):
                    f.write(f"pass {line}\n")


def read_expected(path):
    lanes, cur = {}, None
    for raw in open(path):
        line = raw.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        tag, _, rest = line.partition(" ")
        if tag == "lane":
            cur = lanes.setdefault(rest, {"exit": None, "final": None, "npass": 0, "PASS": collections.Counter(),
                                           "SKIP": collections.Counter(), "FAIL": collections.Counter(),
                                           "targets": collections.Counter()})
        elif tag == "exit":
            cur["exit"] = int(rest)
        elif tag == "final":
            a, b = rest.split()
            cur["final"] = (int(a), int(b))
        elif tag == "npass":
            cur["npass"] = int(rest)
        else:
            cur[{"pass": "PASS", "skip": "SKIP", "fail": "FAIL", "target": "targets"}[tag]][rest] += 1
    return lanes


def compare(lane, exp, got):
    red, info = [], []
    if exp["exit"] is not None and got["exit"] != exp["exit"]:
        red.append(f"exit status {got['exit']}, expected {exp['exit']}")
    if exp["final"] is not None and got["final"] != exp["final"]:
        red.append(f"final suite line {got['final']}, expected {exp['final']}")
    if got["npass"] < exp["npass"]:
        red.append(f"{got['npass']} PASS lines, expected at least {exp['npass']}")
    for line, n in (exp["PASS"] - got["PASS"]).items():
        red.append(f"missing PASS (x{n}): {line}")
    for k, what in (("SKIP", "new SKIP"), ("FAIL", "new FAIL"), ("targets", "new failed make target")):
        for line, n in (got[k] - exp[k]).items():
            red.append(f"{what} (x{n}): {line}")
        for line, n in (exp[k] - got[k]).items():
            info.append(f"expected {k} no longer present (x{n}): {line}")
    extra = got["PASS"] - exp["PASS"]
    if extra:
        info.append(f"{sum(extra.values())} PASS line(s) beyond the baseline")
    counts = (f"{lane}: PASS {got['npass']} SKIP {sum(got['SKIP'].values())} FAIL {sum(got['FAIL'].values())} "
              f"failed-targets {sum(got['targets'].values())} exit {got['exit']}"
              + (f" final {got['final'][0]}/{got['final'][1]}" if got["final"] else ""))
    return counts, red, info


def main(argv):
    if argv[:1] == ["expected-from-logs"]:
        out, specs = argv[1], argv[2:]
        lanes = []
        for spec in specs:
            lane, path, pin = spec.split("=", 1)[0], spec.split("=", 1)[1].split(",")[0], spec.endswith(",pin-exit")
            lanes.append((lane, path, pin))
        write_expected(lanes, out)
        return 0
    if argv[:1] == ["compare"]:
        expected, cetta_dir, specs = argv[1], argv[2], argv[3:]
        exp = read_expected(expected)
        status = 0
        for spec in specs:
            lane, path = spec.split("=", 1)
            counts, red, info = compare(lane, exp[lane], parse(path, cetta_dir))
            print(("GREEN " if not red else "RED   ") + counts)
            for r in red:
                print("  REGRESSION: " + r)
            for i in info:
                print("  note: " + i)
            status |= bool(red)
        return status
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
